export function toCountryCode(location: string | null | undefined): string | null {
  if (!location?.trim()) return null;
  const raw = location.trim();
  if (/^[A-Za-z]{2}$/.test(raw)) return raw.toUpperCase();

  const parts = raw.split(',').map((part) => part.trim()).filter(Boolean);
  const candidates = [...parts].reverse();

  for (const part of candidates) {
    const key = part.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
    const keyRaw = part.toLowerCase();
    if (COUNTRY_ALIASES[keyRaw] || COUNTRY_ALIASES[key]) {
      return COUNTRY_ALIASES[keyRaw] || COUNTRY_ALIASES[key];
    }
    const byName = countries.find(
      (c) => c.name.toLowerCase() === keyRaw || c.name.toLowerCase() === key
    );
    if (byName) return byName.code;
    if (CITY_TO_COUNTRY[keyRaw] || CITY_TO_COUNTRY[key]) {
      return CITY_TO_COUNTRY[keyRaw] || CITY_TO_COUNTRY[key];
    }
  }

  return null;
}

