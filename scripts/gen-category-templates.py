"""
Generates src/components/claim/templates/categoryTemplates.ts + categoryTemplates.css from the
approved category mockups (orive-mockups/build.py + style.css), UNCHANGED except:
  * offers()/links()/cta() emit placeholders that the app fills with real (escaped) data,
  * the ice "From their space" Putney gallery (third-party photos) is dropped,
  * CSS is scoped under .orive-tpl so it cannot leak into the rest of the app.
Usage: python3 scripts/gen-category-templates.py /path/to/orive-mockups
"""
import json, os, re, sys, shutil
M = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "../orive-mockups") + "/"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "components", "claim", "templates")
src = open(M + "build.py").read().split("\nsections=''")[0]
ns = {}; cwd = os.getcwd(); os.chdir(M); exec(src, ns); os.chdir(cwd)
ns["offers"] = lambda l, cls="": f"<!--ORIVE:OFFERS:{cls}-->"
ns["links"] = lambda k: "<!--ORIVE:LINKS-->"
ns["cta"] = lambda t: f"<!--ORIVE:CTA:{t}-->"
tpl = {}
for k in ns["C"]:
    body = ns["body"](k)
    body = re.sub(r"<h2>From their space</h2>.*?</p>", "", body, flags=re.S)
    n, acc, acc2, icon, *_ = ns["C"][k]
    tpl[k] = {"label": n, "accent": acc, "accent2": acc2, "iconSvg": ns["I"](icon), "sample": ns["FB"].get(k, ""), "body": body}
icons = {n: ns["I"](n) for n in ["pin", "globe", "insta", "camera", "shield", "check", "clock", "cal", "phone"]}
css = open(M + "style.css").read()
def scope(css):
    out, i = [], 0
    for m in re.finditer(r"(@keyframes[^{]+\{(?:[^{}]*\{[^}]*\})*\s*\})|([^{}@]+)\{([^}]*)\}", css):
        if m.group(1): out.append(m.group(1)); continue
        sels = [s.strip() for s in m.group(2).split(",") if s.strip()]
        sc = []
        for s in sels:
            if s in ("body", "html", ":root"): sc.append(".orive-tpl")
            elif s == "*": sc.append(".orive-tpl,.orive-tpl *")
            elif s.startswith(".variant") or s.startswith(".dark") or s.startswith(".white") or s.startswith(".wild"): sc.append(f".orive-tpl{s}" if s.startswith(".variant") else f".orive-tpl {s},.orive-tpl{s}")
            else: sc.append(f".orive-tpl {s}")
        out.append(",".join(sc) + "{" + m.group(3) + "}")
    return "\n".join(out)
extra = """
/* app additions (same tokens as orive-drafts/gen.py) */
.orive-tpl.variant{width:auto;max-width:100%;min-height:100vh}
.orive-tpl .banner{background:#f6c34a;color:#000;font-weight:700;padding:10px 32px;display:flex;gap:8px;align-items:center}
.orive-tpl .bio{margin-top:20px}.orive-tpl .bio h3{margin:0 0 6px}.orive-tpl .bio p{margin:0;line-height:1.5}
.orive-tpl .per{margin:2px 0;font-weight:600}
.orive-tpl .avatar.ini{display:grid;place-items:center;background:var(--acc);color:#fff;font-size:40px;font-weight:800}
.orive-tpl .drf{font-size:11px;background:#fde68a;color:#000;padding:2px 6px;border-radius:4px;font-weight:600;margin-left:6px;vertical-align:middle}
.orive-tpl a{color:inherit}.orive-tpl .links a{color:var(--acc)}
.orive-tpl .card .btn{margin-top:10px;padding:10px 20px;font-size:15px;cursor:pointer}
@media (max-width:760px){.orive-tpl .offers,.orive-tpl .aufg,.orive-tpl .heat,.orive-tpl .two,.orive-tpl .bw,.orive-tpl .sg,.orive-tpl .ocs,.orive-tpl .pks{grid-template-columns:1fr!important}.orive-tpl .head{flex-direction:column;align-items:flex-start}.orive-tpl .timeline,.orive-tpl .bigg{flex-wrap:wrap;gap:16px}}
"""
open(os.path.join(OUT, "categoryTemplates.css"), "w").write("/* GENERATED by scripts/gen-category-templates.py – do not edit */\n" + scope(css) + extra)
ts = "// GENERATED by scripts/gen-category-templates.py from the approved orive-mockups – do not edit by hand.\n"
ts += "export type CategoryTemplate = { label: string; accent: string; accent2: string; iconSvg: string; sample: string; body: string };\n"
ts += "export const CATEGORY_TEMPLATES: Record<string, CategoryTemplate> = " + json.dumps(tpl, ensure_ascii=False, indent=1) + ";\n"
ts += "export const TPL_ICONS: Record<string, string> = " + json.dumps(icons, ensure_ascii=False) + ";\n"
ts += 'export const EXAMPLE_BADGE = ' + json.dumps(ns["EX"]) + ";\n"
open(os.path.join(OUT, "categoryTemplates.ts"), "w").write(ts)
pub = os.path.join(os.path.dirname(__file__), "..", "public", "claim", "covers")
os.makedirs(pub, exist_ok=True)
for k in ns["C"]: shutil.copy(M + f"img/cover-{k}.jpg", os.path.join(pub, f"{k}.jpg"))
shutil.copy(M + "img/CREDITS.md", os.path.join(pub, "CREDITS.md"))
print("ok", len(tpl))
