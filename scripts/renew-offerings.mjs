/**
 * Calculates a rolling upcoming date offset from now
 * @param {number} daysFromNow 
 * @param {number} hour 
 * @param {number} minute 
 * @returns {string} ISO Date string
 */
function getUpcomingDate(daysFromNow = 3, hour = 18, minute = 0) {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

/**
 * Rolls forward an existing date if it is in the past, preserving day-of-week & time
 * @param {string} originalDateStr 
 * @param {number} defaultDaysAhead 
 * @returns {string} ISO Date string
 */
export function rollDateForward(originalDateStr, defaultDaysAhead = 4) {
  const now = new Date();
  if (!originalDateStr) {
    return getUpcomingDate(defaultDaysAhead);
  }
  const date = new Date(originalDateStr);
  if (isNaN(date.getTime())) {
    return getUpcomingDate(defaultDaysAhead);
  }
  if (date.getTime() < now.getTime()) {
    const diffMs = now.getTime() - date.getTime();
    // Advance by 7-day increments (preserving weekday and time)
    const weeksToAdd = Math.ceil(diffMs / (7 * 86400000)) + 1;
    date.setTime(date.getTime() + weeksToAdd * 7 * 86400000);
  }
  return date.toISOString();
}

