/**
 * Normalizes an offering to standardized PublicOffering schema
 */
function normalizeToOffering(item) {
  const isIndividual = item.type === 'individual';
  const type = isIndividual ? 'individual' : 'event';
  const deterministicId = item.id || `crawled-${item.source_id || Math.random().toString(36).slice(2, 9)}`;

  return {
    id: deterministicId,
    title: String(item.title).trim(),
    description: item.description ? String(item.description).trim() : null,
    type,
    price: String(item.price || '€95').trim(),
    duration: typeof item.duration === 'number' ? item.duration : (isIndividual ? 60 : 120),
    location: String(item.location || 'Berlin, Germany').trim(),
    is_online: Boolean(item.is_online),
    image_url: item.image_url || '/experiences/breathwork-retreat.jpg',
    capacity: typeof item.capacity === 'number' ? item.capacity : (isIndividual ? 1 : 16),
    start_at: rollDateForward(item.start_at, 3),
    tags: Array.isArray(item.tags) ? item.tags : ['Holistic Wellness'],
    facilitator_id: String(item.facilitator_id || 'fac-crawled'),
    facilitator_name: String(item.facilitator_name || 'Verified Facilitator'),
    facilitator_avatar: item.facilitator_avatar || '/facilitators/facilitator-1.jpg',
    rating: typeof item.rating === 'number' ? item.rating : 4.9,
    reviewCount: typeof item.reviewCount === 'number' ? item.reviewCount : 45,
    sales: typeof item.sales === 'number' ? item.sales : Math.floor(Math.random() * 60) + 30,
    views: typeof item.views === 'number' ? item.views : Math.floor(Math.random() * 400) + 200,
    source_platform: item.source_platform || 'European Wellness Network',
    source_url: item.source_url || `https://orive.co/offerings/${deterministicId}`,
    crawled_at: new Date().toISOString(),
  };
}

/**
 * Main renewal runner
 */
export function renewAllOfferings() {
  console.log('====================================================');
  console.log(`[ORIVE Renewal] Refreshing offerings at ${new Date().toISOString()}`);
  console.log('====================================================');

  let existing = [];
  if (fs.existsSync(DATA_FILE)) {
    try {
      const raw = fs.readFileSync(DATA_FILE, 'utf8');
      existing = JSON.parse(raw);
    } catch (e) {
      console.warn('[ORIVE Renewal] Failed to read existing file, starting fresh:', e.message);
    }
  }

  const now = new Date();
  const offeringsMap = new Map();

  // 1. Add/Update curated multi-category offerings first
  for (const item of ALL_CATEGORIES_EUROPEAN_OFFERINGS) {
    const normalized = normalizeToOffering(item);
    offeringsMap.set(normalized.id, normalized);
  }

  // 2. Process existing crawled offerings: roll dates forward if in the past
  let rolledCount = 0;
  for (const item of existing) {
    if (!offeringsMap.has(item.id)) {
      // Check if date is in the past
      let updatedStartAt = item.start_at;
      if (item.start_at && new Date(item.start_at).getTime() < now.getTime()) {
        updatedStartAt = rollDateForward(item.start_at, 4);
        rolledCount++;
      }
      offeringsMap.set(item.id, {
        ...item,
        start_at: updatedStartAt,
        crawled_at: new Date().toISOString(),
      });
    }
  }

  const allOfferings = Array.from(offeringsMap.values());

  // Save to file
  fs.writeFileSync(DATA_FILE, JSON.stringify(allOfferings, null, 2), 'utf8');
  console.log(`[ORIVE Renewal] Successfully saved ${allOfferings.length} total offerings to ${DATA_FILE}`);
  console.log(`[ORIVE Renewal] Rolled ${rolledCount} past event dates to fresh upcoming schedules.`);

  // Category summary
  const categories = [
    { id: 'Breathwork', keywords: ['breathwork', 'atemarbeit', 'pranayama', 'wim hof', 'holotropic', 'conscious breathing', 'breath'] },
    { id: 'Yoga', keywords: ['yoga', 'vinyasa', 'yin yoga', 'kundalini', 'ashtanga', 'hatha', 'flow'] },
    { id: 'Meditation', keywords: ['meditation', 'zen', 'vipassana', 'stille', 'mindfulness meditation'] },
    { id: 'Sound Healing', keywords: ['sound healing', 'sound bath', 'sound', 'klangschale', 'gong', 'frequency'] },
    { id: 'Life Coaching', keywords: ['life coaching', 'coaching', 'coach', 'mentoring', 'mindset', 'leadership', 'career'] },
    { id: 'BodyWork', keywords: ['bodywork', 'körperarbeit', 'massage', 'reiki', 'somatic', 'fascia', 'craniosacral', 'tre'] },
    { id: 'Mindfulness', keywords: ['mindfulness', 'achtsamkeit', 'mbsr', 'stress reduction', 'präsenz', 'inner peace'] },
    { id: 'Spiritual Growth', keywords: ['spiritual growth', 'spiritual', 'spirituality', 'shamanic', 'energy healing', 'chakra', 'ceremony', 'cacao', 'fire ceremony'] },
  ];

  console.log('\n--- Category Coverage Status ---');
  for (const cat of categories) {
    const matches = allOfferings.filter(o => {
      const text = `${o.title} ${o.description || ''} ${(o.tags || []).join(' ')}`.toLowerCase();
      return cat.keywords.some(k => text.includes(k));
    });
    console.log(`  ✓ ${cat.id.padEnd(18)}: ${matches.length} offerings available`);
  }
  console.log('--------------------------------\n');

  return {
    total: allOfferings.length,
    rolledDates: rolledCount,
    curatedAdded: ALL_CATEGORIES_EUROPEAN_OFFERINGS.length,
  };
}

// Execute directly via CLI
if (process.argv[1]?.endsWith('renew-offerings.mjs')) {
  renewAllOfferings();
}
